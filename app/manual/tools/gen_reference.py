def gen_ext_knobs(root: str) -> str:
    """The QWEN38_* knobs the conductor reads inside an engine: the names and defaults of the engine
    contract's engine-ext-v1/knobs.json (tandemapp/knobs.py DEFAULTS is held equal to it by the
    tests), and the module of tandemapp/ that reads each one (not the kit the model copies)."""
    with open(os.path.join(root, "contracts", "engine-ext-v1", "knobs.json"), encoding="utf-8") as fh:
        defaults = json.load(fh)["knobs"]
    names = sorted(defaults)
    readers: dict = {}
    for dp, dn, fn in os.walk(os.path.join(root, "tandemapp")):
        dn[:] = [x for x in dn if x not in ("__pycache__", "laya_kit")]
        for f in fn:
            rel = os.path.relpath(os.path.join(dp, f), root)
            if not f.endswith(".py") or rel == "tandemapp/knobs.py":
                continue
            with open(os.path.join(dp, f), encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            for name in names:
                if re.search(r"""\.get\(\s*["']""" + name + r"""["']""", text):
                    readers.setdefault(name, []).append(rel)
    lines = [HEADER, r"\begin{reftable}{The QWEN38\_* knobs the conductor reads inside an engine (engine-ext-v1 knobs.json)}{tab:ref-ext-knobs}{\hd{Variable} & \hd{Code default} & \hd{read in}}"]
    for name in names:
        d = defaults.get(name, "")
        d = "none" if d in (None, "") else str(d)
        lines.append(code("QWEN38_" + name) + " & " + code(d) + " & " + code(", ".join(sorted(readers.get(name, []))[:2])) + r" \\")
    lines.append(r"\end{reftable}")
    return "\n".join(lines) + "\n"


def scan_vars(root: str, prefix: str, dirs: tuple) -> dict:
    """Every PREFIX_NAME the code mentions, with the files that mention it."""
    pat = re.compile(r"\b" + prefix + r"_[A-Z0-9_<>]*[A-Z0-9>]\b")
    found: dict = {}
    for d in dirs:
        base = os.path.join(root, d)
        paths = []
        if os.path.isfile(base):
            paths = [base]
        else:
            for dp, dn, fn in os.walk(base):
                dn[:] = [x for x in dn if x not in ("node_modules", "dist", "__pycache__", "tests", "e2e", "mock")]
                paths += [os.path.join(dp, f) for f in fn if f.endswith((".py", ".sh", ".env", ".example", ".ts", ".service"))]
        for p in paths:
            try:
                with open(p, encoding="utf-8", errors="replace") as fh:
                    text = fh.read()
            except OSError:
                continue
            for name in set(pat.findall(text)):
                found.setdefault(name, set()).add(os.path.relpath(p, root))
    return found


def gen_qse_vars(root: str) -> str:
    found = scan_vars(root, "QSE", QSE_DIRS)
    lines = [HEADER, r"\begin{reftabletwo}{QSE\_* variables TandemApp's code reads}{tab:ref-qse}{\hd{Variable} & \hd{Read in}}"]
    for name in sorted(found):
        files = sorted(found[name])
        shown = ", ".join(files[:3]) + (f" and {len(files) - 3} more" if len(files) > 3 else "")
        lines.append(code(name) + " & " + code(shown) + r" \\")
    lines.append(r"\end{reftabletwo}")
    return "\n".join(lines) + "\n"


def gen_tandem_vars(root: str) -> str:
    """TANDEM_* variables: the proxy's documented list first, then every other one the code reads."""
    with open(os.path.join(root, "proxy/config.py"), encoding="utf-8") as fh:
        doc = ast.get_docstring(ast.parse(fh.read())) or ""
    documented = []
    cur = None
    for line in doc.splitlines():
        m = re.match(r"^\s{4}(TANDEM_[A-Z0-9_<>n]+)=(\S*)\s*(.*)$", line)
        if m:
            cur = [m.group(1), m.group(2), m.group(3)]
            documented.append(cur)
        elif cur and re.match(r"^\s{40,}\S", line):
            cur[2] = (cur[2] + " " + line.strip()).strip()
        else:
            cur = None
    found = scan_vars(root, "TANDEM", TANDEM_DIRS)
    seen = {d[0] for d in documented}
    lines = [HEADER, r"\begin{reftable}{TANDEM\_* variables: the proxy, the collector and the plugins}{tab:ref-tandem}{\hd{Variable} & \hd{Example} & \hd{What it sets}}"]
    for name, example, desc in documented:
        ex = "(a key)" if re.search(r"\b(?:s[k]|tdm)-", example) else example
        if ex.startswith("http") and not ex.startswith("https://api."):
            ex = "(a URL)"
        lines.append(code(name) + " & " + code(ex.strip('"')) + " & " + tex(clean(desc, 200)) + r" \\")
    for name in sorted(found):
        if name in seen or "<" in name:
            continue
        files = sorted(found[name])
        lines.append(code(name) + " & & read in " + code(", ".join(files[:2])) + r" \\")
    lines.append(r"\end{reftable}")
    return "\n".join(lines) + "\n"


def gen_metrics(root: str) -> str:
    # tandemapp/metrics.py also holds the engine's own families, which the engine's manual lists:
    # of those, the ones the engine contract marks "owner": "ext" are the extension's
    with open(os.path.join(root, "contracts", "engine-api-v1", "metrics-families.json"), encoding="utf-8") as fh:
        owner = {f["name"]: f["owner"] for f in json.load(fh)["families"]}
    rows = []
    for rel in ("tandemapp/metrics.py", "proxy/service.py", "proxy/engines.py", "proxy/hostcollect.py"):
        try:
            tree = parse(root, rel)
        except (OSError, SyntaxError):
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call) or not node.args:
                continue
            fn = node.func.attr if isinstance(node.func, ast.Attribute) else getattr(node.func, "id", "")
            if fn not in ("Counter", "Gauge", "Histogram"):
                continue
            name = lit(node.args[0])
            if not isinstance(name, str) or not name.startswith(("qse_", "tandem_")):
                continue
            if rel == "tandemapp/metrics.py" and owner.get(name) != "ext":
                continue
            helps = help_text(node.args[1]) if len(node.args) > 1 else ""
            labels = lit(node.args[2]) if len(node.args) > 2 else lit(kw(node, "labels"), ())
            if not isinstance(labels, (list, tuple)):
                labels = ()
            rows.append((name, fn.lower(), ", ".join(labels), helps, rel))
    seen, uniq = set(), []
    for r in rows:
        if r[0] not in seen:
            seen.add(r[0])
            uniq.append(r)
    lines = [HEADER, r"\begin{reftable}{Prometheus families TandemApp registers: the conductor's inside an engine, the proxy's and the collector's}{tab:ref-metrics}{\hd{Metric} & \hd{Type, labels} & \hd{What it counts}}"]
    for name, kind, labels, helps, rel in uniq:
        lab = kind + ((", " + labels) if labels else "")
        lines.append(code(name) + " & " + code(lab) + " & " + mono_inline(clean(helps, 200)) + r" \\")
    lines.append(r"\end{reftable}")
    return "\n".join(lines) + "\n"


