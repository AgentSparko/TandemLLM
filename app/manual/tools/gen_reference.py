#!/usr/bin/env python3
"""Generate the reference tables of TandemApp's manual from the code, so they stay in sync with it.

    python3 manual/tools/gen_reference.py              # writes manual/generated/*.tex
    python3 manual/tools/gen_reference.py --root DIR   # read the code of another checkout
    python3 manual/tools/gen_reference.py --check      # exit 1 when a committed file is stale
                                                       # or the HTTP reference misses something

TandemApp's copy of the engine's manual/tools/gen_reference.py (ENG-413): the tables of TandemApp's
code, which left the engine's manual when the two manuals were split. The proxy's argument
parsers, the QWEN38_* knobs the conductor reads inside an engine (the engine contract's
engine-ext-v1/knobs.json, with tandemapp/knobs.py's defaults), the QSE_* and TANDEM_* variables
TandemApp's code reads, its metric registrations, the controller's ledger and its route tables.
The HTTP reference (routes, headers, errors: tools/http_ref.py) is written by hand and checked
against the code, as in the engine's copy.

It never imports the project: every table comes from parsing the source with `ast` or from plain
text. Standard library only, Python 3.9 or newer.
"""

